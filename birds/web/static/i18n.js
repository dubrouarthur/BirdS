export function makeT(getLang) {
  return (key, vars) => {
    const lang = getLang();
    let text = STRINGS[lang]?.[key] ?? STRINGS.fr[key] ?? key;
    if (vars)
      for (const [name, value] of Object.entries(vars))
        text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}
